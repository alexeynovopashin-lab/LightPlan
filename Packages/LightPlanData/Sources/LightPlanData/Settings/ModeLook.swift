import Foundation

/// Что режим показывает вне настроек (30г.9). Сами настройки — `SettingsView.root(mode)` (30г.8), пять переключателей
/// «Астро» — `AppSettings.sees` (30г.4–7). Строки описи `docs/30g2_modes_table.md` (ветка `wt/30g-2-modes-recalc`),
/// столбец «Просто», и ответы Алексея 05.11 (DECISIONS «Три режима: пять ответов по описи 30г.2»):
/// - ответ 3: в «Просто» цветное небо купола есть (№ 55), ленты суток нет (№ 68, 87);
/// - ответ 1 описи 31.10: подменю уходят, инструменты остаются — нет меню слоёв «Карты» (№ 71), «Настроить карточку»
///   (№ 131–134), шестерёнки «Мои жанры» в форме (№ 150–151), строки «Самоочистка» в корзине мудборда (№ 179);
/// - ответ 2: выбор, сделанный в «Про», в «Просто» продолжает действовать — здесь ничего не пишется и не сбрасывается
///   (порядок блоков карточки, список жанров, срок корзины остаются как записаны). Исключение одно: без меню слоёв солнце,
///   компас и «Мои места» на «Карте» горят всегда (`alwaysOnMapLayers`), какой бы выбор ни стоял; вернувшись в «Про»,
///   человек видит свои слои.
/// В «Про» и «Астро» всё это есть, как до 30г.9.
public struct ModeLook: Equatable, Sendable {
    /// Цветное небо купола по глубине сумерек (№ 55): во всех режимах.
    public let domeSky: Bool
    /// Лента суток под таймбаром «Света» и «Карты» (№ 68, 87).
    public let dayRibbon: Bool
    /// Кнопка слоёв «Карты» и её меню (№ 71).
    public let mapLayersMenu: Bool
    /// «Настроить карточку» в шапке карточки: тумблеры блоков, ручки, «По умолчанию» / «Готово» (№ 131–134).
    public let cardTuning: Bool
    /// Шестерёнка у «Жанра» в форме → «Мои жанры» с длительностью и сроком сдачи (№ 150–151).
    public let myGenres: Bool
    /// Строка «Самоочистка» в корзине мудборда (№ 179).
    public let binAutoClean: Bool

    public init(_ mode: AppMode) {
        let full = mode != .simple
        domeSky = true
        dayRibbon = full
        mapLayersMenu = full
        cardTuning = full
        myGenres = full
        binAutoClean = full
    }

    /// Слои «Карты», которые горят, что бы ни было записано (№ 72, 75, 76; исключение ответа 2): без меню их нечем
    /// вернуть. Имена — ключи `mapLayers` снимка (`MapLayers.Key` в UI).
    public var alwaysOnMapLayers: [String] { mapLayersMenu ? [] : ["sun", "compass", "spots"] }
}

public extension AppSettings {
    /// Что текущий режим показывает вне настроек (30г.9).
    var look: ModeLook { ModeLook(mode) }
}
