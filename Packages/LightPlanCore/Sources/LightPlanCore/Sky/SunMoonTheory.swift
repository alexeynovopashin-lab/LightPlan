/// Положения Солнца и Луны для слоёв AR (шаг 29.8в.21): координаты **даты**, пригодные для `SkyFrame`.
///
/// Веб считает Солнце по NOAA (склонение и уравнение времени один раз на сутки) и Луну по Меёсу с одним членом
/// возмущения — для «Света» этого хватает, и стенд паритета держит именно эти числа. На экране AR диск стоит там,
/// где его снимают, поэтому здесь отдельные теории: Меёс, «Astronomical Algorithms», гл. 25 (Солнце, ≈ 0,01°) и
/// гл. 47 в сокращении (Луна, 35 членов долготы и 30 широты, ≈ 0,03°). Против JPL Horizons — `SkyTimeTests`.
/// Нутация не учтена (≤ 0,005°): звёздное время `SkyFrame` тоже среднее.
enum SunMoonTheory {

    private static func rad(_ d: Double) -> Double { d * Double.pi / 180 }

    /// Эклиптические долгота и широта (радианы) → экваториальные на средний экватор даты, наклон `eps` (градусы).
    private static func equatorial(lon: Double, lat: Double, eps: Double) -> EquatorialPoint {
        let e = rad(eps)
        return EquatorialPoint(
            ra: atan2(sin(lon) * cos(e) - tan(lat) * sin(e), cos(lon)),
            dec: asin(sin(lat) * cos(e) + cos(lat) * sin(e) * sin(lon)))
    }

    /// Средний наклон эклиптики на дату, градусы (Meeus 22.2), `t` — юлианские века от J2000.
    private static func obliquity(_ t: Double) -> Double { 23.4392911 - 0.0130042 * t - 1.64e-7 * t * t + 5.04e-7 * t * t * t }

    /// Видимое положение Солнца (Meeus 25.2–25.9): уравнение центра, аберрация. `days` — дни от J2000.
    static func sun(days: Double) -> EquatorialPoint {
        let t = days / 36_525
        let l0 = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
        let m = rad(357.52911 + 35999.05029 * t - 0.0001537 * t * t)
        let c = (1.914602 - 0.004817 * t - 0.000014 * t * t) * sin(m) + (0.019993 - 0.000101 * t) * sin(2 * m)
            + 0.000289 * sin(3 * m)
        let omega = rad(125.04 - 1934.136 * t)
        let lon = rad(l0 + c - 0.00569 - 0.00478 * sin(omega))
        return equatorial(lon: lon, lat: 0, eps: obliquity(t) + 0.00256 * cos(omega))
    }

    /// Луна из центра Земли: положение на средний экватор даты и расстояние, км.
    static func moon(days: Double) -> (point: EquatorialPoint, distance: Double) {
        let t = days / 36_525
        func arg(_ c0: Double, _ c1: Double, _ c2: Double, _ c3: Double, _ c4: Double) -> Double {
            rad((c0 + c1 * t + c2 * t * t + c3 * t * t * t + c4 * t * t * t * t).truncatingRemainder(dividingBy: 360))
        }
        let lp = arg(218.3164477, 481267.88123421, -0.0015786, 1 / 538_841, -1 / 65_194_000)
        let d = arg(297.8501921, 445267.1114034, -0.0018819, 1 / 545_868, -1 / 113_065_000)
        let m = arg(357.5291092, 35999.0502909, -0.0001536, 1 / 24_490_000, 0)
        let mp = arg(134.9633964, 477198.8675055, 0.0087414, 1 / 69_699, -1 / 14_712_000)
        let f = arg(93.2720950, 483202.0175233, -0.0036539, -1 / 3_526_000, 1 / 863_310_000)
        let a1 = rad(119.75 + 131.849 * t), a2 = rad(53.09 + 479264.290 * t), a3 = rad(313.45 + 481266.484 * t)
        let e = 1 - 0.002516 * t - 0.0000074 * t * t

        func sum(_ rows: [(Int, Int, Int, Int, Double)], _ fn: (Double) -> Double) -> Double {
            rows.reduce(0) { acc, r in
                let ef = abs(r.1) == 2 ? e * e : (r.1 == 0 ? 1 : e)
                let a = Double(r.0) * d + Double(r.1) * m + Double(r.2) * mp + Double(r.3) * f
                return acc + r.4 * ef * fn(a)
            }
        }
        // (D, M, M', F, коэффициент): долгота и расстояние — 10⁻⁶° и 10⁻³ км; широта — 10⁻⁶°.
        let sl = sum(longitude, sin) + 3958 * sin(a1) + 1962 * sin(lp - f) + 318 * sin(a2)
        let sb = sum(latitude, sin) - 2235 * sin(lp) + 382 * sin(a3) + 175 * sin(a1 - f) + 175 * sin(a1 + f)
            + 127 * sin(lp - mp) - 115 * sin(lp + mp)
        let sr = sum(distance, cos)
        let lon = lp + rad(sl / 1e6), lat = rad(sb / 1e6)
        return (equatorial(lon: lon, lat: lat, eps: obliquity(t)), 385_000.56 + sr / 1000)
    }

