import LightPlanDomain
import LightPlanData

/// Что из неба видно на экранах, по переключателям «Астро» (опись 30г.2 § 2). Правило одно — `AppSettings.sees`;
/// здесь оно только переводится на язык экранов: слои «Карты» и AR, плитки пожеланий формы, пожелания карточки.
/// Данные не меняются: слой, выключенный переключателем, в файле остаётся как был, пожелание «Луна» в съёмке — тоже,
/// их только не показывают (30г.6: «Луны нет в «Про»» значит «не показываем», а не «выключили»).
extension AppModel {

    /// Переключатель «Луна» (30г.6): только «Астро» и только включённый. Экраны «Света», «Карты» и AR читают копию
    /// в `LightScreenModel.moon`, ставит её `applySettings` из того же правила.
    var seesMoon: Bool { settings.sees(.moon) }

    /// Слои «Карты», которые рисуются сейчас: то, что включено в меню слоёв, без того, что прячет переключатель.
    /// Слой «Луна» — только с «Луной» (опись № 73).
    var mapLayersShown: MapLayers {
        var l = mapLayers
        if !seesMoon { l.moon = false }
        return l
    }

    /// Пункты меню слоёв «Карты»: без «Луны» строки «Луна» нет вовсе (опись № 73).
    var mapLayerKeys: [MapLayers.Key] {
        MapLayers.Key.allCases.filter { $0 != .moon || seesMoon }
    }

    /// Слои неба AR, которые разрешают переключатели. «Луна» — 30г.6 (опись № 104); звёзды, созвездия, планеты и
    /// Млечный Путь ждут своих переключателей (30г.7) и пока разрешены всегда.
    var arSkyLayers: Set<SunARSkyLayer> {
        Set(SunARSkyLayer.allCases.filter { $0 != .moon || seesMoon })
    }

    /// Пожелания, о которых экраны говорят: без «Луны» пожелание «Луна» молчит (опись № 147, 203), но в записи остаётся.
    func shownWishes(_ wishes: [Wish]) -> [Wish] {
        seesMoon ? wishes : wishes.filter { $0 != .moon }
    }

    /// Плитки «Нужна погода» в форме: без «Луны» восемь из девяти (опись № 165).
    var wishTiles: [Wish] { shownWishes(Wish.allCases) }
}
